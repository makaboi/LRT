"""Cinematic retro dark-fantasy artwork for Part I.

Every scene uses the same restrained visual language: outlines, broken planes,
silhouettes, weather, and negative space.  Scene names belong in the interface,
not inside the pictures.  The drawings stay within a 64-column stage so their
composition survives a standard macOS Terminal window.
"""


class AnimatedArtwork(str):
    """A string-compatible still image with optional restrained motion frames."""

    frames: tuple[str, ...]

    def __new__(cls, still: str, frames: tuple[str, ...]) -> "AnimatedArtwork":
        instance = super().__new__(cls, still)
        instance.frames = frames
        return instance


